// 翻译 hook
export function useTranslation() {
    const locale = useLocaleStore((s) => s.locale)
    const t = (key: string, fallback?: string): string => {
        return (
            translations[locale]?.[key] ??
            translations['zh-cn']?.[key] ??
            fallback ??
            key
        )
    }
    return { t, locale }
}

